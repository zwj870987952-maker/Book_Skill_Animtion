c1 = """# 能力卡: 时空双轴标尺与原画轨目表设计 (Timing, Spacing & Inbetweening Charts)

## Rationale (核心原理)
在动画物理学与工程学中，时间（Timing）与空间幅度（Spacing）是构成一切运动感知的两大根本维度。
理查德·威廉姆斯（Richard Williams）在《动画师生存手册》开篇立下第一公理：
> **“Timing is the speed of an action (how many frames it takes); Spacing is the path and distribution of speed (how far things move from frame to frame)!”（时间是动作的速度，即消耗多少帧；空间是速度的路径与分布，即帧与帧之间位移多大距离！）**

很多初学者甚至 CG 动画师经常混淆二者：
- 如果动作看起来太快或太慢，这是**时间（Timing）**的问题，需要增减摄影表（Dope Sheet）上的总帧数；
- 如果动作看起来僵死、沉重、轻飘或缺乏弹性，这是**空间幅度（Spacing）**的问题，需要调整帧与帧之间的距离分布比例！
轨目表（Spacing Chart）是原画师指挥中间画与计算机曲线的核心数学工程工具。

## Instruction (轨目表设计与时空编排四步规程)

### 1. 均等 vs. 慢入慢出 vs. 偏心倾向轨目心智模型
```
  [ 1. 匀速机械运动 (Equal Spacing - 传送带/发条玩具) ]
  极值 1 |----- 2 ----- 3 ----- 4 ----- 5 ----- 6 -----| 极值 7
  位移均匀等分，毫无力量蓄势与缓冲，缺乏生命感。

  [ 2. 慢入慢出 (Slow-In & Slow-Out - 经典重力与阻尼运动) ]
  极值 1 |-2-3---4-------5-------6---7-8-| 极值 9
  两端密集 (缓冲)，中间稀疏 (高速撕裂)，呈现弹性做功。

  [ 3. 偏心倾向 (Favored Breakdown - 单侧爆发释能) ]
  极值 1 |-2-3-4---5---------6-----------| 极值 7
  极度偏向起始端极值 1，随后呈指数级暴冲至极值 7。
```

### 2. 轨目表构建实战四步流
1. **确立起止极值与总时间（Establish Extremes & Timing）**:
   - 确定起始姿态（如 Frame 1）与目标姿态（如 Frame 13），总耗时 12 帧（0.5秒）；
2. **绘制过渡核心原画（Select Breakdown Position）**:
   - 在两张极值中间确立黄金过渡点（如 Frame 7）；
3. **标注轨目表分支与倾向（Mark Spacing Chart & Favors）**:
   - 在画纸边缘画一条直线，标出 1 与 7，在靠近 1 的一侧标出 3、5（Slow-Out），并在靠近 7 的一侧标出偏向；
4. **一拍一（On Ones） vs. 一拍二（On Twos）决策**:
   - 常规行走与中速动作一律采用“一拍二”（每秒 12 张画），节省绘制成本并获得稳定视觉暂留；
   - 快速挥拳、高速奔跑、剧烈镜头摇移与残影涂抹必须采用“一拍一”（每秒 24 张画），杜绝跳帧断裂。

## Actionable Example (调校一个角色挥拳出击的轨目表)
1. **起始帧（Frame 1）**: 拳头收在胸前蓄力；
2. **目标帧（Frame 9）**: 拳头全力刺穿前方空气；
3. **编排轨目表**:
   - 严禁均等插值！
   - Frame 1 到 5 极度密集（慢出蓄力）：1 - 2 - 3 距离极短；
   - Frame 5 到 7 发生爆发性撕裂（跨越大半个屏幕）；
   - Frame 7 到 9 拳头由于关节锁死产生微小过冲缓冲；
4. **结果**: 动作在前 4 帧充满精钢弹簧般的张力，第 5 帧瞬间炸裂出拳，视觉冲击力十足。

## Constraints (约束与禁止)
- **严禁均等中割（No Equal Inbetweening）**: 除非模拟传送带或机械齿轮，任何生物运动严禁等距离分割；
- **严禁无轨目盲目中割**: 每一张极值原画边缘必须具备清晰的轨目表标注，严禁凭感觉随机插值。

## Verification (验收标准)
- **速度曲线平滑度**: 速度与位移的一阶导数（速度）与二阶导数（加速度）曲线无阶跃尖峰，加减速过渡有机自然；
- **拍数一致性**: 在同一动作段落中，主躯干与核心肢体的拍数（On Ones 或 On Twos）匹配严密，无抖动频闪。
"""
