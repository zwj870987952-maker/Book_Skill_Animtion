c2 = """# 能力卡: 关键帧、极值帧与过渡原画层级工程 (Keys, Extremes & Breakdowns)

## Rationale (核心原理)
很多初学者以为动画制作就是“从第 1 帧一张一张画到第 100 帧”（Straight Ahead 连续画法）。这种方法极难控制角色的体积、节奏与叙事焦点，经常画到一半角色就走样缩水或动作拖沓失控。
理查德·威廉姆斯与迪士尼传奇前辈确立了动画工业级的分级装配流水线：
1. **关键帧（Keys）**: 决定故事概念与戏剧转折的黄金姿态（The Story Point）；
2. **极值帧（Extremes）**: 空间几何位移的最远点、最高点与最低点（The Outer Limits of Movement）；
3. **过渡原画（Breakdowns / Passing）**: 决定两张极值之间运动弧线与身体优先倾向的关键中间画（The Defining Arc & Favor）；
4. **中间画（Inbetweens）**: 机械或半机械的中割填补。

威廉姆斯的大师箴言是：
> **“The Breakdown is the most important drawing! It decides which way the movement goes and what parts lead or lag!”（过渡原画是全片最重要的一张画！它决定了动作走哪条弧线，以及身体各部位谁先动谁滞后！）**

## Instruction (动画动作分级构建四步规程)

### 1. 动画分级架构心智模型
```
  [ 1. 关键帧 Keys (故事与意图) ] --------> 角色受惊倒退 (叙事原点)
                  |
                  v
  [ 2. 极值帧 Extremes (空间几何极限) ] --> 最高伸展帧 (Frame 1) vs. 最低着地帧 (Frame 11)
                  |
                  v
  [ 3. 过渡原画 Breakdowns (弧线与滞后) ] -> 决定走下弧 (下沉蓄力) 还是走上弧 (惊恐腾空)
                  |
                  v
  [ 4. 中间画 Inbetweens (轨目补间) ] ----> 依据轨目表完成平滑过渡
```

### 2. 分级原画实战四步流
1. **确立关键帧（The Keys）**:
   - 捕捉叙事动机，画出最能表达角色心理与剧情的起止姿态，确定角色的戏剧潜台词；
2. **定位空间极值帧（The Extremes）**:
   - 找到动作在空间中到达的最远端（如伸展极限、压缩极限、跳跃最高点），标记帧号；
3. **精心设计过渡原画（The Breakdown - 灵魂之笔）**:
   - 确定动作路径走圆滑弧线（下沉弧或上探弧）；
   - 确定主动力源与滞后部位（如骨盆先行，头部与双臂滞后）；
   - 确立倾向（Favor）：该过渡帧更偏向 Extreme A 还是 Extreme B；
4. **下发轨目表并执行中间画（Inbetweening）**:
   - 标注轨目图，执行 1/2 二分法或缓动中割。

## Actionable Example (调校角色从站立到坐下的动作)
1. **关键帧 A（Frame 1）**: 角色笔直站立在椅子前；
2. **关键帧 B（Frame 15）**: 角色完全坐在椅子上；
3. **极值点分析**:
   - 如果直接从 1 中割到 15，角色会像电梯一样斜线滑落，毫无重力感；
4. **设计过渡原画 Breakdown（Frame 7）**:
   - 角色屁股向后翘出并下沉，膝盖弯曲，但**上半身向前剧烈倾斜以维持重心中轴平衡**，头部略微向上保持视线平视；
   - 赋予该 Breakdown 走一条“先下沉后向后平移”的饱满下弧；
5. **结果**: 角色展现出真实的生物重力代偿与平衡做功，动作生动可信。

## Constraints (约束与禁止)
- **严禁跳过 Breakdown 直接做中割**: 两个极值帧之间若没有经过精心设计的 Breakdown，计算机插值或画师中割必然走生硬直线；
- **严禁极值点位置漂移**: 极值帧一旦确立，中间画严禁随意超越极值点的空间边界，防止体积与空间穿模。

## Verification (验收标准)
- **弧线检查**: 鼻尖、手腕与骨盆的运动轨迹连线是否呈现平滑圆润的弧线，无折角畸变；
- **灵魂可测性**: 抽掉所有中间画，仅凭 Key + Extreme + Breakdown 3-4 张原画连续翻动，是否已能完整传达动作的力量与质感。
"""
